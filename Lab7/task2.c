/* Найбільші припустимі вимірності матриць. Межа масиву в мові C має бути сталим виразом часу компіляції,
   а змінна з модифікатором const ним не є, тому розмір задано директивою
   препроцесора. */
#define MAX_ROWS 20 /* видів продукції   */
#define MAX_COLS 20 /* підприємств       */

/* Ширини колонок таблиць у символах. */
enum
{
    LABEL_WIDTH = 16,  /* "Продукція N" у таблиці обсягів          */
    COLUMN_WIDTH = 10, /* стовпець підприємства в таблиці обсягів  */
    TOTAL_WIDTH = 12,  /* колонка "Разом" у таблиці обсягів        */
    NAME_WIDTH = 18,   /* "Підприємство N" / "Продукція N" у звітах */
    VALUE_WIDTH = 18,  /* сумарний обсяг у звіті а)                */
    DELTA_WIDTH = 14,  /* зміна обсягу у звіті б)                  */
    CHANGES_WIDTH = 50 /* ширина таблиць звіту б) разом з оцінкою  */
};

/*------------------------------------------------------------------------------
  utf8Width - ширина рядка в символах, а не в байтах.

  У кодуванні UTF-8 кирилична літера займає два байти, тому специфікатор
  формату виду %-16s, який рахує байти, вирівнює заголовки таблиць
  неправильно. Функція рахує лише початкові байти символів: у продовжувальних
  байтах старші біти дорівнюють 10 у двійковій системі.

  Параметри: s [вхідний] - рядок у кодуванні UTF-8.
  Повертає : кількість символів рядка.
------------------------------------------------------------------------------*/
int utf8Width(const char *s)
{
    int width = 0;

    for (const unsigned char *p = (const unsigned char *)s; *p != '\0'; ++p)
    {
        /* Продовжувальний байт UTF-8 має вигляд 10xxxxxx: маска 0xC0 лишає
           два старші біти, і якщо вони не дорівнюють 10, це початок символу. */
        if ((*p & 0xC0) != 0x80)
        {
            ++width;
        }
    }

    return width;
}

/*------------------------------------------------------------------------------
  printPadded - вивести рядок, доповнивши його пропусками до заданої ширини.

  Параметри:
      s     [вхідний] - рядок, що виводиться;
      width [вхідний] - потрібна ширина поля в символах;
      left  [вхідний] - true: вирівнювання ліворуч; false: праворуч.

  Локальні змінні:
      pad - кількість пропусків, які треба додати.
------------------------------------------------------------------------------*/
void printPadded(const char *s, int width, bool left)
{
    const int pad = width - utf8Width(s);

    if (!left)
    {
        for (int i = 0; i < pad; ++i)
        {
            putchar(' ');
        }
    }

    printf("%s", s);

    if (left)
    {
        for (int i = 0; i < pad; ++i)
        {
            putchar(' ');
        }
    }
}

/*------------------------------------------------------------------------------
  skipLine - відкинути залишок рядка введення разом із символом '\n'.
------------------------------------------------------------------------------*/
void skipLine(void)
{
    int c = getchar();

    while (c != '\n' && c != EOF)
    {
        c = getchar();
    }
}

/*------------------------------------------------------------------------------
  restOfLineOk - перевірити залишок рядка після успішно прочитаного числа.

  Припустимі лише пропуски до кінця рядка або до наступного числа (так
  рядок матриці "1 2 3 4" читається як чотири елементи чотирма викликами
  readInt); будь-який інший символ - помилка, і решта рядка відкидається.

  Повертає : true - залишок рядка коректний; false - у рядку зайві символи.
------------------------------------------------------------------------------*/
bool restOfLineOk(void)
{
    int c = getchar();

    while (c == ' ' || c == '\t' || c == '\r')
    {
        c = getchar();
    }
    if (c == '\n' || c == EOF)
    {
        return true;
    }
    if (isdigit(c) || c == '-' || c == '+')
    {
        ungetc(c, stdin);
        return true;
    }

    skipLine();
    return false;
}

/*------------------------------------------------------------------------------
  readInt - прочитати ціле число із заданого діапазону з контролем введення.

  Параметри: prompt [вхідний], value [вихідний], low, high [вхідні].
  Повертає : true - число прочитано; false - вхідні дані вичерпано.

  Число поза діапазоном, не число або зайві символи після числа в тому
  самому рядку - помилка з повторним запитом; кілька чисел в одному рядку
  через пропуск приймаються по одному за кожен виклик.
------------------------------------------------------------------------------*/
bool readInt(const char *prompt, int *value, int low, int high)
{
    for (;;)
    {
        printf("%s", prompt);
        const int scanned = scanf("%d", value);

        if (scanned == EOF)
        {
            return false;
        }

        if (scanned == 0)
        {
            skipLine();
        }
        else if (restOfLineOk() && *value >= low && *value <= high)
        {
            return true;
        }

        printf("Помилка: потрібне ціле число від %d до %d.\n", low, high);
    }
}

/*------------------------------------------------------------------------------
  fillMatrix - заповнити матрицю обсягів продукції.

  Параметри:
      a    [вихідний] - матриця, що заповнюється;
      n    [вхідний]  - кількість рядків (видів продукції);
      m    [вхідний]  - кількість стовпців (підприємств);
      name [вхідний]  - назва матриці для запрошень;
      byHand [вхідний] - true: введення з клавіатури; false: генерація;
      low, high [вхідні] - межі діапазону для генерації.
  Повертає : true - заповнено; false - вхідні дані вичерпано.
------------------------------------------------------------------------------*/
bool fillMatrix(long long a[][MAX_COLS], int n, int m, const char *name, bool byHand,
                int low, int high)
{
    if (byHand)
    {
        printf("Уведіть обсяги для матриці %s; рядок - вид продукції, "
               "стовпець - підприємство:\n",
               name);

        for (int i = 0; i < n; ++i)
        {
            for (int j = 0; j < m; ++j)
            {
                char prompt[80];
                snprintf(prompt, sizeof prompt,
                         "  продукція %d, підприємство %d: ", i + 1, j + 1);
                int volume = 0;
                if (!readInt(prompt, &volume, 0, INT_MAX))
                {
                    return false;
                }
                a[i][j] = volume;
            }
        }
    }
    else
    {
        /* Масштабування rand() на діапазон замість rand() % range: стандарт гарантує
           лише RAND_MAX >= 32767, і для ширшого діапазону остача не охопила б
           усіх значень. */
        for (int i = 0; i < n; ++i)
        {
            for (int j = 0; j < m; ++j)
            {
                /* Розмах у double: high - low + 1 може не вміститися в int. */
                const double range = (double)high - low + 1.0;
                a[i][j] = low + (long long)((double)rand() / ((double)RAND_MAX + 1.0) *
                                            range);
            }
        }
    }
    return true;
}

/*------------------------------------------------------------------------------
  printSeparator - вивести розділювальну лінію таблиці.
  Параметри: width [вхідний] - довжина лінії в символах.
------------------------------------------------------------------------------*/
void printSeparator(int width)
{
    printf("  ");
    for (int i = 0; i < width; ++i)
    {
        putchar('-');
    }
    printf("\n");
}

/*------------------------------------------------------------------------------
  printMatrix - вивести матрицю обсягів у табличному вигляді із заголовками
                рядків (види продукції) та стовпців (підприємства).

  Праворуч виводяться підсумки рядків, унизу - підсумки стовпців.

  Параметри:
      title [вхідний] - заголовок таблиці;
      a     [вхідний] - матриця;
      n, m  [вхідні]  - кількість рядків і стовпців.

  Локальні змінні:
      tableWidth - повна ширина таблиці для розділювальних ліній;
      label      - підпис рядка ("Продукція N").

  Параметр-матрицю оголошено без const: у C до редакції C23 масив
  long long a[N][M] неявно не перетворюється на const long long (*)[M].
------------------------------------------------------------------------------*/
void printMatrix(const char *title, long long a[][MAX_COLS], int n, int m)
{
    printf("\n%s\n", title);

    /* Сума модулів усіх елементів обмежує зверху будь-який підсумок таблиці,
       тож за довжиною її запису зі знаком обирається ширина стовпців: для
       звичайних обсягів лишаються стандартні ширини, для великих стовпці
       розширюються, щоб числа не зливалися. */
    long long bound = 0;
    for (int i = 0; i < n; ++i)
    {
        for (int j = 0; j < m; ++j)
        {
            bound += llabs(a[i][j]);
        }
    }
    const int needed = snprintf(NULL, 0, "%lld", -bound) + 2;
    const int columnWidth = needed > COLUMN_WIDTH ? needed : COLUMN_WIDTH;
    const int totalWidth = needed > TOTAL_WIDTH ? needed : TOTAL_WIDTH;

    const int tableWidth = LABEL_WIDTH + columnWidth * m + totalWidth;

    printf("  ");
    printPadded("Продукція \\ П-во", LABEL_WIDTH, true);
    for (int j = 0; j < m; ++j)
    {
        printf("%*d", columnWidth, j + 1);
    }
    printPadded("Разом", totalWidth, false);
    printf("\n");

    printSeparator(tableWidth);

    for (int i = 0; i < n; ++i)
    {
        char label[LABEL_WIDTH * 2];
        snprintf(label, sizeof label, "Продукція %d", i + 1);
        printf("  ");
        printPadded(label, LABEL_WIDTH, true);

        long long rowTotal = 0;
        for (int j = 0; j < m; ++j)
        {
            printf("%*lld", columnWidth, a[i][j]);
            rowTotal += a[i][j];
        }
        printf("%*lld\n", totalWidth, rowTotal);
    }

    printSeparator(tableWidth);
    printf("  ");
    printPadded("Разом", LABEL_WIDTH, true);

    long long grandTotal = 0;
    for (int j = 0; j < m; ++j)
    {
        long long columnTotal = 0;
        for (int i = 0; i < n; ++i)
        {
            columnTotal += a[i][j];
        }
        printf("%*lld", columnWidth, columnTotal);
        grandTotal += columnTotal;
    }
    printf("%*lld\n", totalWidth, grandTotal);
}

/*------------------------------------------------------------------------------
  addMatrices - поелементна сума двох матриць: c[i][j] = a[i][j] + b[i][j].

  Параметри:
      a, b [вхідні]   - доданки;
      c    [вихідний] - результат;
      n, m [вхідні]   - кількість рядків і стовпців.
------------------------------------------------------------------------------*/
void addMatrices(long long a[][MAX_COLS], long long b[][MAX_COLS],
                 long long c[][MAX_COLS], int n, int m)
{
    for (int i = 0; i < n; ++i)
    {
        for (int j = 0; j < m; ++j)
        {
            c[i][j] = a[i][j] + b[i][j];
        }
    }
}

/*------------------------------------------------------------------------------
  subtractMatrices - поелементна різниця двох матриць: c[i][j] = a[i][j] - b[i][j].

  Параметри:
      a    [вхідний]  - зменшуване;
      b    [вхідний]  - від'ємник;
      c    [вихідний] - результат;
      n, m [вхідні]   - кількість рядків і стовпців.
------------------------------------------------------------------------------*/
void subtractMatrices(long long a[][MAX_COLS], long long b[][MAX_COLS],
                      long long c[][MAX_COLS], int n, int m)
{
    for (int i = 0; i < n; ++i)
    {
        for (int j = 0; j < m; ++j)
        {
            c[i][j] = a[i][j] - b[i][j];
        }
    }
}

/*------------------------------------------------------------------------------
  reportTotalsByPlant - пункт а) умови: сумарний обсяг продукції за два квартали
                        по кожному підприємству.

  Параметри:
      a, b [вхідні] - обсяги випуску за I та II квартали;
      n    [вхідний] - кількість видів продукції (рядків);
      m    [вхідний] - кількість підприємств (стовпців).

  Локальні змінні:
      totalByPlant - сумарний обсяг по кожному підприємству;
      grandTotal   - підсумок по всіх підприємствах;
      label        - підпис рядка таблиці ("Підприємство N").
------------------------------------------------------------------------------*/
void reportTotalsByPlant(long long a[][MAX_COLS], long long b[][MAX_COLS], int n, int m)
{
    long long totalByPlant[MAX_COLS];
    long long grandTotal = 0;

    for (int j = 0; j < m; ++j)
    {
        totalByPlant[j] = 0;
        for (int i = 0; i < n; ++i)
        {
            totalByPlant[j] += a[i][j] + b[i][j];
        }
        grandTotal += totalByPlant[j];
    }

    printf("\n============================================================\n");
    printf("а) Сумарний обсяг продукції за два квартали по підприємствах\n\n");
    printf("  ");
    printPadded("Підприємство", NAME_WIDTH, true);
    printPadded("Обсяг за I+II кв.", VALUE_WIDTH, false);
    printf("\n");
    printSeparator(NAME_WIDTH + VALUE_WIDTH);

    for (int j = 0; j < m; ++j)
    {
        char label[48];
        snprintf(label, sizeof label, "Підприємство %d", j + 1);
        printf("  ");
        printPadded(label, NAME_WIDTH, true);
        printf("%*lld\n", VALUE_WIDTH, totalByPlant[j]);
    }

    printSeparator(NAME_WIDTH + VALUE_WIDTH);
    printf("  ");
    printPadded("Разом", NAME_WIDTH, true);
    printf("%*lld\n", VALUE_WIDTH, grandTotal);
}

/*------------------------------------------------------------------------------
  changeLabel - словесна оцінка зміни обсягу за її знаком.

  Параметри: delta [вхідний] - зміна обсягу (II квартал мінус I).
  Повертає : "приріст" для додатної зміни, "зменшення" для від'ємної,
             "без змін" для нульової.
------------------------------------------------------------------------------*/
const char *changeLabel(long long delta)
{
    if (delta > 0)
    {
        return "приріст";
    }
    if (delta < 0)
    {
        return "зменшення";
    }
    return "без змін";
}

/*------------------------------------------------------------------------------
  reportChanges - пункт б) умови: приріст або зменшення обсягів за другий
                  квартал порівняно з першим, за видами продукції та по
                  підприємствах.

  Параметри:
      a, b [вхідні] - обсяги випуску за I та II квартали;
      n, m [вхідні] - кількість видів продукції та підприємств.

  Локальні змінні:
      deltaByProduct - зміна обсягу за кожним видом продукції;
      deltaByPlant   - зміна обсягу по кожному підприємству;
      label          - підпис рядка таблиці.
------------------------------------------------------------------------------*/
void reportChanges(long long a[][MAX_COLS], long long b[][MAX_COLS], int n, int m)
{
    long long deltaByProduct[MAX_ROWS];
    long long deltaByPlant[MAX_COLS];

    for (int i = 0; i < n; ++i)
    {
        deltaByProduct[i] = 0;
        for (int j = 0; j < m; ++j)
        {
            deltaByProduct[i] += b[i][j] - a[i][j];
        }
    }

    for (int j = 0; j < m; ++j)
    {
        deltaByPlant[j] = 0;
        for (int i = 0; i < n; ++i)
        {
            deltaByPlant[j] += b[i][j] - a[i][j];
        }
    }

    printf("\n============================================================\n");
    printf("б) Приріст (+) або зменшення (-) обсягів за II квартал\n");
    printf("   порівняно з I кварталом\n");

    printf("\n  За видами продукції:\n  ");
    printPadded("Вид продукції", NAME_WIDTH, true);
    printPadded("Зміна обсягу", DELTA_WIDTH, false);
    printf("   Оцінка\n");
    printSeparator(CHANGES_WIDTH);

    for (int i = 0; i < n; ++i)
    {
        char label[48];
        snprintf(label, sizeof label, "Продукція %d", i + 1);
        printf("  ");
        printPadded(label, NAME_WIDTH, true);
        printf("%+*lld   %s\n", DELTA_WIDTH, deltaByProduct[i],
               changeLabel(deltaByProduct[i]));
    }

    printf("\n  По підприємствах:\n  ");
    printPadded("Підприємство", NAME_WIDTH, true);
    printPadded("Зміна обсягу", DELTA_WIDTH, false);
    printf("   Оцінка\n");
    printSeparator(CHANGES_WIDTH);

    for (int j = 0; j < m; ++j)
    {
        char label[48];
        snprintf(label, sizeof label, "Підприємство %d", j + 1);
        printf("  ");
        printPadded(label, NAME_WIDTH, true);
        printf("%+*lld   %s\n", DELTA_WIDTH, deltaByPlant[j],
               changeLabel(deltaByPlant[j]));
    }
}

/*------------------------------------------------------------------------------
  Головна функція. Читає обидві матриці обсягів, обчислює сумарні обсяги
  за два квартали та приріст/зменшення за другий квартал.

  Локальні змінні:
      a, b       - обсяги продукції за перший та другий квартали;
      sum, diff  - проміжні матриці A + B та B - A;
      n, m       - кількість видів продукції та підприємств;
      fillChoice - пункт меню способу задання елементів (1 або 2);
      byHand     - спосіб задання елементів матриць;
      low, high  - межі діапазону для генерації;
      modeChoice - пункт меню режиму виведення (1 або 2);
      verbose    - режим виведення: true - з проміжними обчисленнями.
------------------------------------------------------------------------------*/
int main(void)
{
    printf("Лабораторна робота №7, завдання 2 (варіант 19)\n");
    printf("Виконав: студент групи ІПЗ-11 Одарчук Олексій\n");
    printf("Обсяги випуску продукції за два квартали\n\n");
    printf("Рядок матриці - вид продукції, стовпець - підприємство.\n\n");

    int n = 0;
    int m = 0;
    if (!readInt("Уведіть кількість видів продукції n (1..20): ", &n, 1, MAX_ROWS) ||
        !readInt("Уведіть кількість підприємств m (1..20):   ", &m, 1, MAX_COLS))
    {
        return 1;
    }

    printf("\nСпосіб задання обсягів:\n"
           "  1 - введення з клавіатури\n"
           "  2 - генерація псевдовипадкових чисел у заданому діапазоні\n");

    int fillChoice = 0;
    if (!readInt("Оберіть спосіб (1..2): ", &fillChoice, 1, 2))
    {
        return 1;
    }

    const bool byHand = (fillChoice == 1);
    int low = 0;
    int high = 0;

    if (!byHand)
    {
        if (!readInt("Уведіть нижню межу обсягу: ", &low, 0, INT_MAX) ||
            !readInt("Уведіть верхню межу обсягу: ", &high, low, INT_MAX))
        {
            return 1;
        }
        srand((unsigned)time(NULL));
    }

    printf("\nРежим виведення результатів:\n"
           "  1 - тільки кінцевий результат\n"
           "  2 - з проміжними обчисленнями\n");

    int modeChoice = 0;
    if (!readInt("Оберіть режим (1..2): ", &modeChoice, 1, 2))
    {
        return 1;
    }

    const bool verbose = (modeChoice == 2);

    /* Обсяги зберігаються в long long: кожен уводиться як int, але сума двох
       кварталів і різниця можуть вийти за межі int. */
    long long a[MAX_ROWS][MAX_COLS];
    long long b[MAX_ROWS][MAX_COLS];
    if (!fillMatrix(a, n, m, "A (I квартал)", byHand, low, high) ||
        !fillMatrix(b, n, m, "B (II квартал)", byHand, low, high))
    {
        return 1;
    }

    printMatrix("Матриця A - обсяги випуску за I квартал", a, n, m);
    printMatrix("Матриця B - обсяги випуску за II квартал", b, n, m);

    if (verbose)
    {
        long long sum[MAX_ROWS][MAX_COLS];
        addMatrices(a, b, sum, n, m);
        printMatrix("Проміжний результат: матриця A + B (обсяги за два квартали)\n"
                    "(підсумки стовпців - сумарні обсяги по підприємствах)",
                    sum, n, m);
    }

    reportTotalsByPlant(a, b, n, m);

    if (verbose)
    {
        long long diff[MAX_ROWS][MAX_COLS];
        subtractMatrices(b, a, diff, n, m);
        printMatrix("Проміжний результат: матриця B - A (зміна обсягів)\n"
                    "(підсумки рядків - зміна за видами продукції, "
                    "підсумки стовпців - по підприємствах)",
                    diff, n, m);
    }

    reportChanges(a, b, n, m);

    return 0;
}
